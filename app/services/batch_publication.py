"""Digitalização e Publicação em Lote: thin orchestration of two existing pipelines.

1. Processing is the Geração em Lote queue (BatchStore + datasheet worker): supplier PDFs are
   read, technical data extracted and the Portuguese datasheet generated by the existing pipeline.
2. Each processed SKU becomes a validated PRM package (manifest + hashes, same layout as
   digitalization_storage.finalize_draft) built in memory from the batch outputs: processed
   photos, the PRM datasheet and permitted technical documents. The supplier datasheet is a
   source only and is never packaged.
3. The package is handed internally to the Cadastro via API queue (Jobs.create), which keeps
   identification, manifest/hash validation, Dry Run, approval, grants, audit and recovery.

No commercial name, description, category, attribute or CSV is produced here.
"""
import hashlib
import io
import json
import tempfile
import time
import uuid
import zipfile
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from app.services.datasheet_batches import BatchStore, relative_name
from app.services.digitalization_storage import _document_name, validate_sku
from app.services.registration_package import process_image
from app.services.store_registration_jobs import Jobs
from app.services.store_registration_plan import prepare_files

SCHEMA = """
CREATE TABLE IF NOT EXISTS pipelines(id TEXT PRIMARY KEY,org TEXT,owner TEXT,company TEXT,datasheet_batch TEXT,created REAL);
CREATE TABLE IF NOT EXISTS pipeline_items(pipeline TEXT,sku TEXT,item INTEGER,store_batch TEXT,handed REAL,PRIMARY KEY(pipeline,sku,store_batch));
"""
READY = {"done", "review"}
PROCESSING = {"pending": "Aguardando início", "queued": "Na fila", "running": "Processando", "done": "Concluído",
              "review": "Concluído com pendências", "error": "Erro", "invalid": "Inválido"}
STORE = {"preview_queued": "Dry Run na fila", "preview_running": "Consultando loja", "review": "Pronto para aprovação",
         "blocked": "Bloqueado", "awaiting_product": "Aguardando cadastro por CSV", "queued": "Publicação na fila",
         "running": "Publicando", "done": "Publicado e verificado", "error": "Erro", "uncertain": "Reconciliação manual"}


def stage(processing, store, approval):
    """Stepper position: 1 importação … 6 verificação."""
    if store == "done": return 6
    if store in {"queued", "running", "uncertain"}: return 5
    if store == "review" and approval: return 4
    if store: return 3
    return 2 if processing in {"queued", "running", "done", "review", "error"} else 1


class Pipelines:
    def __init__(self, app_settings, store_settings, *, jobs=None, batches=None):
        self.store_settings = store_settings
        self.batches = batches or BatchStore(app_settings)
        self.jobs = jobs or Jobs()
        with self.jobs.db() as db:
            db.executescript(SCHEMA)

    # --- Importação ---------------------------------------------------------------------
    def create(self, raw, company, org, owner, root=""):
        """Folder identification only (SKU = exact folder name, zeros preserved). Reuses BatchStore intake."""
        self.store_settings.credentials(company, "wc")  # fail early if the store is not configured
        batch = self.batches.create(raw, org, owner, identification="folder", company=company, root=root)
        identifier = uuid.uuid4().hex
        with self.jobs.db() as db:
            db.execute("INSERT INTO pipelines VALUES(?,?,?,?,?,?)", (identifier, str(org), str(owner), company, batch, time.time()))
        return identifier

    def record(self, identifier, org, owner):
        with self.jobs.db() as db:
            row = db.execute("SELECT * FROM pipelines WHERE id=? AND org=? AND owner=?", (identifier, str(org), str(owner))).fetchone()
        if not row: raise LookupError("Lote não encontrado.")
        return dict(row)

    def history(self, org, owner):
        with self.jobs.db() as db:
            return [dict(r) for r in db.execute("SELECT id,company,created FROM pipelines WHERE org=? AND owner=? ORDER BY created DESC LIMIT 100",
                                                (str(org), str(owner)))]

    # --- Processamento (existing queue and worker) ---------------------------------------
    def process(self, identifier, org, owner, model, items=None, retry=False):
        record = self.record(identifier, org, owner)
        self.batches.enqueue(record["datasheet_batch"], org, owner, model, retry=retry, items=items)

    def pause(self, identifier, org, owner):
        record = self.record(identifier, org, owner)
        return self.batches.pause(record["datasheet_batch"], org, owner)

    # --- Organização dos arquivos ----------------------------------------------------------
    def package(self, record, item, org, owner):
        """In-memory validated package for one processed SKU. Never contains the supplier datasheet."""
        sku = validate_sku(item["codigo"])
        if item["state"] not in READY or not item["download"]:
            raise ValueError("Datasheet ainda não gerado para " + sku + ".")
        batch_folder = self.batches.folder(record["datasheet_batch"])
        pdf, _ = self.batches.output_file(record["datasheet_batch"], item["id"], org, owner)
        files, warnings = {}, []
        with tempfile.TemporaryDirectory() as temporary:
            folder = Path(temporary) / sku
            folder.mkdir()
            for asset in item.get("assets", []):
                if asset["role"] == "source_datasheet":
                    continue  # input of the generator only; stays in the batch storage
                target = folder / relative_name(asset["name"])
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes((batch_folder / asset["stored"]).read_bytes())
            # Legacy Playwright naming rules decide main image, gallery order and document roles.
            plan = prepare_files(folder, sku)
            warnings += plan["warnings"]
            images = ([plan["main_image"]] if plan["main_image"] else []) + plan["gallery"]
            ordered = []
            for index, path in enumerate(images, 1):
                name = f"Fotos/{sku}_variante.jpg" if index == 1 else f"Fotos/{sku}_foto{index}.jpg"
                files[name] = ("main_image" if index == 1 else "gallery", process_image(Path(path).read_bytes()), Path(path).name)
                ordered.append(name)
            files[f"{sku}_Datasheet.pdf"] = ("generated_datasheet", pdf.read_bytes(), "datasheet.pdf")
            counts = Counter()
            for document in plan["downloads"]:
                original = Path(document["path"]).name
                for role in dict.fromkeys([document["role"], "other"]):
                    if role in {"source_datasheet", "generated_datasheet"}: continue
                    try:
                        name = _document_name(sku, role, original, counts[role] + 1)
                    except ValueError:
                        continue
                    counts[role] += 1
                    files[name] = (role, Path(document["path"]).read_bytes(), original)
                    break
                else:
                    warnings.append(f"{original}: formato não suportado no pacote; preservado nas fontes do lote.")
        analysis = pdf.parent / "analysis.json"
        if analysis.is_file():
            files["datasheet_dados.json"] = ("technical_analysis", analysis.read_bytes(), "analysis.json")
        manifest = {"schema_version": 1, "package_id": f"{record['datasheet_batch']}:{item['id']}", "package_version": 1,
                    "status": "validated", "generated_at": datetime.now(timezone.utc).isoformat(),
                    "company": record["company"], "cigam_code": sku, "sku": sku, "product_name": item.get("nome") or sku,
                    "source": {"datasheet_batch": record["datasheet_batch"], "item": item["id"], "folder": item.get("folder")},
                    "ordered_images": ordered,
                    "files": [{"role": role, "path": path, "sha256": hashlib.sha256(content).hexdigest(), "original_name": original}
                              for path, (role, content, original) in files.items()]}
        return sku, files, manifest, warnings

    def archive(self, identifier, org, owner, skus=None):
        """One ZIP with a SKU folder per package: handed to the publication queue or exported as backup."""
        record = self.record(identifier, org, owner)
        detail = self.batches.detail(record["datasheet_batch"], org, owner)
        selected = [i for i in detail["items"] if i["state"] in READY and i["download"] and (skus is None or i["codigo"] in skus)]
        if skus is not None and {i["codigo"] for i in selected} != set(skus):
            raise ValueError("SKU selecionado sem datasheet gerado.")
        if not selected: raise ValueError("Nenhum produto com datasheet gerado.")
        stream, packaged, warnings = io.BytesIO(), [], {}
        with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_DEFLATED) as output:
            for item in selected:
                sku, files, manifest, notes = self.package(record, item, org, owner)
                for path, (_, content, _) in files.items():
                    output.writestr(f"{sku}/{path}", content)
                output.writestr(f"{sku}/manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
                packaged.append((sku, item["id"]))
                warnings[sku] = notes
        return stream.getvalue(), packaged, warnings

    # --- Integração interna: Dry Run do Cadastro via API ----------------------------------
    def handoff(self, identifier, org, owner, skus=None):
        """Create the publication batch in memory; no download/re-upload. Already handed SKUs are skipped."""
        record = self.record(identifier, org, owner)
        with self.jobs.db() as db:
            handed = {r[0] for r in db.execute("SELECT sku FROM pipeline_items WHERE pipeline=?", (identifier,))}
        detail = self.batches.detail(record["datasheet_batch"], org, owner)
        ready = [i["codigo"] for i in detail["items"] if i["state"] in READY and i["download"] and i["codigo"] not in handed]
        selection = ready if skus is None else [s for s in skus if s in ready]
        if skus is not None and len(selection) != len(set(skus)):
            raise ValueError("SKU já enviado para revisão ou sem datasheet gerado.")
        if not selection: raise ValueError("Nenhum produto novo pronto para revisão.")
        raw, packaged, _ = self.archive(identifier, org, owner, selection)
        store_batch = self.jobs.create(record["company"], org, owner, None, raw, self.store_settings,
                                       identification="folder", archive_name="publicacao-lote.zip")
        with self.jobs.db() as db:
            db.executemany("INSERT INTO pipeline_items VALUES(?,?,?,?,?)",
                           [(identifier, sku, item, store_batch, time.time()) for sku, item in packaged])
            for sku, _ in packaged:
                self.jobs.audit(store_batch, sku, owner, "handoff", {"pipeline": identifier, "datasheet_batch": record["datasheet_batch"]}, db)
        return store_batch

    def links(self, identifier):
        with self.jobs.db() as db:
            return {r["sku"]: r["store_batch"] for r in db.execute(
                "SELECT sku,store_batch FROM pipeline_items WHERE pipeline=? ORDER BY handed", (identifier,))}

    def by_store_batch(self, identifier, skus):
        groups = {}
        for sku, store_batch in self.links(identifier).items():
            if skus is None or sku in skus:
                groups.setdefault(store_batch, []).append(sku)
        if skus is not None and sum(len(v) for v in groups.values()) != len(set(skus)):
            raise ValueError("SKU sem Dry Run neste lote.")
        return groups

    # --- Aprovação, publicação e retomada (each product isolated) ---------------------------
    def each(self, identifier, org, owner, skus, action):
        self.record(identifier, org, owner)
        results = []
        for store_batch, selection in self.by_store_batch(identifier, skus).items():
            try:
                results.append({"skus": selection, "ok": True, "value": action(store_batch, selection)})
            except (ValueError, LookupError) as exc:
                results.append({"skus": selection, "ok": False, "error": str(exc)})
        return results

    def approve(self, identifier, org, owner, skus=None, replace_main=()):
        def action(store_batch, selection):
            with self.jobs.db() as db:
                ready = [r[0] for r in db.execute("SELECT sku FROM jobs WHERE batch=? AND state='review'", (store_batch,)) if r[0] in selection]
            if not ready: raise ValueError("Nenhum Dry Run pronto para aprovação.")
            return self.jobs.approve(store_batch, org, owner, ready, [s for s in replace_main if s in ready])
        return self.each(identifier, org, owner, skus, action)

    def publish(self, identifier, org, owner, skus=None):
        """Queues approved items. The publisher policy/grants still decide; production stays blocked without grants."""
        return self.each(identifier, org, owner, skus,
                         lambda store_batch, selection: self.jobs.confirm(store_batch, org, owner, self.store_settings, selection))

    def resume(self, identifier, org, owner):
        """Re-runs Dry Run for errors and 'Aguardando cadastro por CSV'. Uploads already done are reused by identity."""
        return self.each(identifier, org, owner, None, lambda store_batch, _: self.jobs.reprocess(store_batch, org, owner))

    # --- Gestão -------------------------------------------------------------------------
    def overview(self, identifier, org, owner):
        record = self.record(identifier, org, owner)
        detail = self.batches.detail(record["datasheet_batch"], org, owner)
        links = self.links(identifier)
        stores = {b: {i["sku"]: i for i in self.jobs.detail(b, org, owner)["items"]} for b in set(links.values())}
        rows = []
        for item in detail["items"]:
            sku = item["codigo"]
            store = stores.get(links.get(sku), {}).get(sku)
            dry = (store or {}).get("dry_run") or {}
            assets = item.get("assets", [])
            datasheet = ("Gerado" if item["state"] == "done" and item["download"] else
                         "Gerado com pendências" if item["state"] == "review" and item["download"] else
                         "Falhou" if item["state"] in {"error", "invalid"} else "Pendente")
            # Names/descriptions are not produced by this flow, so the intake's name warning does not apply.
            warnings = [w for w in item.get("warnings") or [] if not w.startswith("Nome não informado")]
            issues = [m for m in [item.get("error"), *warnings, (store or {}).get("error"), *(store or {}).get("blockers", [])] if m]
            rows.append({
                "sku": sku, "item": item["id"], "company": record["company"], "folder": item.get("folder"),
                "images": sum(a["role"] == "image" for a in assets),
                "documents": sum(a["role"] not in {"image", "source_datasheet"} for a in assets),
                "processing": item["state"], "processing_label": PROCESSING.get(item["state"], item["state"]),
                "datasheet": datasheet, "pdf": item["download"],
                "store": store["state"] if store else None, "store_label": STORE.get(store["state"], store["state"]) if store else "Não preparado",
                "store_batch": links.get(sku), "product_id": (store or {}).get("product_id"),
                "uploads": sum(a["action"] == "upload" for a in dry.get("images", {}).get("actions", [])),
                "documents_add": sum(a["action"] == "add" for a in dry.get("documents", {}).get("actions", [])),
                "ignored": [i["name"] for i in dry.get("ignored", [])],
                "approved": bool((store or {}).get("approval")), "grant": (store or {}).get("homologation_grant"),
                "write_gate": dry.get("write_gate"), "result": (store or {}).get("result"),
                "audit": (store or {}).get("audit", [])[-8:], "issues": issues,
                "stage": stage(item["state"], store["state"] if store else None, (store or {}).get("approval")),
            })
        stages = Counter(r["stage"] for r in rows)
        return {"id": identifier, "company": record["company"], "created": record["created"],
                "datasheet_batch": record["datasheet_batch"], "processing": detail["state"], "progress": detail["progress"],
                "total": len(rows), "stages": {str(k): stages.get(k, 0) for k in range(1, 7)},
                "published": sum(r["store"] == "done" for r in rows), "items": rows}
